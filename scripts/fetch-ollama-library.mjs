// Snapshots the Ollama library into app/utils/ollamaLibrary.ts, and each
// model's readme into static/quickstart/ollama/<name>.md.
//
// ollama.com has no CORS-enabled API, so the deploy page's quick start
// searches this snapshot and reads the readmes as static files. Rerun when
// the library has moved on:
//
//   node scripts/fetch-ollama-library.mjs
import { mkdir, rm, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const OUT = fileURLToPath(
  new URL("../app/utils/ollamaLibrary.ts", import.meta.url),
);
const README_DIR = fileURLToPath(
  new URL("../static/quickstart/ollama/", import.meta.url),
);
const ORIGIN = "https://ollama.com";

const decode = (text) =>
  text
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'");

const html = await (
  await fetch("https://ollama.com/library?sort=popular")
).text();
const entries = [
  ...html.matchAll(/<li[^>]*>\s*<a href="\/library\/([^"]+)"([\s\S]*?)<\/li>/g),
];

const models = entries.flatMap(([, name, body]) => {
  const description = decode(
    body.match(/<p class="max-w-lg[^"]*">([\s\S]*?)<\/p>/)?.[1].trim() ?? "",
  );
  const chips = [
    ...body.matchAll(
      /<span[^>]*class="inline-flex[^"]*"[^>]*>([^<]*)<\/span>/g,
    ),
  ].map((m) => m[1].trim());
  const sizes = chips.filter((chip) => /^(\d+x|e)?[\d.]+[bm]$/.test(chip));
  const capabilities = chips.filter(
    (chip) => !sizes.includes(chip) && chip !== "cloud",
  );
  // A cloud-only model has no weights to pull, so it cannot run on a node.
  if (!sizes.length && chips.includes("cloud")) return [];
  return [{ name, description, sizes, capabilities }];
});

if (models.length < 50)
  throw new Error(
    `Only ${models.length} models parsed; has ollama.com changed its markup?`,
  );

const header = `// Generated by scripts/fetch-ollama-library.mjs on ${new Date().toISOString().slice(0, 10)}; do not edit.
// The Ollama library, most pulled first.
export interface OllamaLibraryModel {
  name: string;
  description: string;
  /** The parameter-size tags, as on ollama.com ("8b", "2x7b"); empty when the model has one size. */
  sizes: string[];
  capabilities: string[];
}

export const OLLAMA_LIBRARY: OllamaLibraryModel[] = `;

await writeFile(OUT, `${header}${JSON.stringify(models, null, 2)};\n`);
console.log(`Wrote ${models.length} models to ${OUT}`);

/* ---------- The readmes ---------- */

// The page renders the readme's markdown as plain HTML (p, h2-h4, lists,
// pre, a, img, strong, em); this turns that back into markdown.
const inline = (node) =>
  node
    .replace(
      /<a [^>]*href="([^"]*)"[^>]*>([\s\S]*?)<\/a>/g,
      (_, href, text) => `[${inline(text)}](${new URL(href, ORIGIN).href})`,
    )
    .replace(
      /<img [^>]*src="([^"]*)"[^>]*alt="([^"]*)"[^>]*\/?>/g,
      (_, src, alt) => `![${alt}](${new URL(src, ORIGIN).href})`,
    )
    .replace(
      /<img [^>]*src="([^"]*)"[^>]*\/?>/g,
      (_, src) => `![](${new URL(src, ORIGIN).href})`,
    )
    .replace(/<(strong|b)>([\s\S]*?)<\/\1>/g, "**$2**")
    .replace(/<(em|i)>([\s\S]*?)<\/\1>/g, "*$2*")
    .replace(/<code>([\s\S]*?)<\/code>/g, "`$1`")
    .replace(/<br\s*\/?>/g, "\n")
    .replace(/<[^>]+>/g, "")
    .replace(/\s+/g, " ")
    .trim();

const toMarkdown = (html) => {
  const blocks = [];
  const pattern =
    /<h([1-6])>([\s\S]*?)<\/h\1>|<pre>(?:<code[^>]*>)?([\s\S]*?)(?:<\/code>)?<\/pre>|<(ul|ol)>([\s\S]*?)<\/\4>|<p>([\s\S]*?)<\/p>|<table>([\s\S]*?)<\/table>/g;
  for (const match of html.matchAll(pattern)) {
    const [, level, heading, code, listTag, list, paragraph, table] = match;
    if (heading !== undefined) {
      blocks.push(`${"#".repeat(Number(level))} ${inline(heading)}`);
    } else if (code !== undefined) {
      blocks.push(`\`\`\`\n${decode(code).trimEnd()}\n\`\`\``);
    } else if (list !== undefined) {
      const items = [...list.matchAll(/<li>([\s\S]*?)<\/li>/g)].map(
        ([, item], index) =>
          `${listTag === "ol" ? `${index + 1}.` : "-"} ${inline(item)}`,
      );
      blocks.push(items.join("\n"));
    } else if (paragraph !== undefined) {
      const text = inline(paragraph);
      if (text) blocks.push(text);
    } else if (table !== undefined) {
      const rows = [...table.matchAll(/<tr>([\s\S]*?)<\/tr>/g)].map(([, row]) =>
        [...row.matchAll(/<t[hd][^>]*>([\s\S]*?)<\/t[hd]>/g)].map(([, cell]) =>
          inline(cell),
        ),
      );
      if (!rows.length) continue;
      const line = (cells) => `| ${cells.join(" | ")} |`;
      blocks.push(
        [
          line(rows[0]),
          line(rows[0].map(() => "---")),
          ...rows.slice(1).map(line),
        ].join("\n"),
      );
    }
  }
  return decode(blocks.join("\n\n")).trim();
};

const readme = async (name) => {
  const page = await (await fetch(`${ORIGIN}/library/${name}`)).text();
  const start = page.indexOf('id="display"');
  if (start < 0) return "";
  // The display div closes where its nesting returns to zero.
  let depth = 0;
  for (const match of page.slice(start).matchAll(/<div\b|<\/div>/g)) {
    depth += match[0] === "</div>" ? -1 : 1;
    if (depth === 0) return toMarkdown(page.slice(start, start + match.index));
  }
  return "";
};

await rm(README_DIR, { recursive: true, force: true });
await mkdir(README_DIR, { recursive: true });
let written = 0;
const queue = [...models];
await Promise.all(
  Array.from({ length: 8 }, async () => {
    for (let model = queue.shift(); model; model = queue.shift()) {
      const markdown = await readme(model.name);
      if (!markdown) continue;
      await writeFile(`${README_DIR}${model.name}.md`, `${markdown}\n`);
      written += 1;
    }
  }),
);
console.log(`Wrote ${written} readmes to ${README_DIR}`);
